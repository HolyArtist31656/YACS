package yacsim.core.ballistics;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import org.wpilib.math.geometry.Pose3d;
import org.wpilib.math.geometry.Rotation3d;
import org.wpilib.math.geometry.Translation3d;
import yacsim.core.physics.BoundingBox3d;
import yacsim.core.util.MinimalJson;

/**
 * Static 3D oriented bounding box (OBB) representing a field obstacle (such as a Hub base, Reef,
 * Truss, or Wall) or a 3D scoring target volume (such as a Hub opening or Speaker mouth).
 *
 * @param name Unique obstacle or target name.
 * @param localBounds Local axis-aligned bounding box in meters.
 * @param pose Field-frame 3D pose of the obstacle.
 * @param scoringTarget {@code true} if intersecting this volume counts as a scored shot rather than
 *     a blocked collision.
 */
public record FieldObstacle3d(
    String name, BoundingBox3d localBounds, Pose3d pose, boolean scoringTarget) {

  /** Compact constructor validating non-null fields. */
  public FieldObstacle3d {
    Objects.requireNonNull(name, "name");
    Objects.requireNonNull(localBounds, "localBounds");
    pose = pose == null ? new Pose3d() : pose;
  }

  /**
   * Convenience factory for an axis-aligned field obstacle defined directly in field coordinates.
   *
   * @param name Obstacle name.
   * @param fieldBounds Axis-aligned field bounds in meters.
   * @return Non-scoring {@link FieldObstacle3d}.
   */
  public static FieldObstacle3d axisAlignedObstacle(String name, BoundingBox3d fieldBounds) {
    return new FieldObstacle3d(name, fieldBounds, new Pose3d(), false);
  }

  /**
   * Convenience factory for an axis-aligned 3D scoring target volume defined in field coordinates.
   *
   * @param name Target name (for example {@code "BlueHubTarget"}).
   * @param fieldBounds Axis-aligned target bounds in meters.
   * @return Scoring {@link FieldObstacle3d}.
   */
  public static FieldObstacle3d axisAlignedTarget(String name, BoundingBox3d fieldBounds) {
    return new FieldObstacle3d(name, fieldBounds, new Pose3d(), true);
  }

  /**
   * Loads a list of {@link FieldObstacle3d} definitions from a {@code yacsim-field.json} file
   * generated by {@code tools/onshape-field-exporter/}.
   *
   * @param fieldJsonPath Path to {@code yacsim-field.json}.
   * @return Immutable list of parsed 3D field obstacles and scoring targets.
   * @throws IOException If reading or parsing the file fails.
   */
  @SuppressWarnings("unchecked")
  public static List<FieldObstacle3d> loadFieldManifest(Path fieldJsonPath) throws IOException {
    Objects.requireNonNull(fieldJsonPath, "fieldJsonPath");
    String text = Files.readString(fieldJsonPath, StandardCharsets.UTF_8);
    Map<String, Object> root = (Map<String, Object>) MinimalJson.parse(text);
    List<Object> rawList = (List<Object>) root.get("obstacles");
    if (rawList == null) {
      return List.of();
    }
    List<FieldObstacle3d> result = new ArrayList<>(rawList.size());
    for (Object obj : rawList) {
      Map<String, Object> item = (Map<String, Object>) obj;
      String name = String.valueOf(item.getOrDefault("name", "Obstacle"));
      boolean target = Boolean.TRUE.equals(item.get("scoringTarget"));
      List<Object> mn = (List<Object>) item.get("minMeters");
      List<Object> mx = (List<Object>) item.get("maxMeters");
      if (mn == null || mx == null || mn.size() < 3 || mx.size() < 3) {
        continue;
      }
      BoundingBox3d bounds =
          new BoundingBox3d(
              ((Number) mn.get(0)).doubleValue(),
              ((Number) mn.get(1)).doubleValue(),
              ((Number) mn.get(2)).doubleValue(),
              ((Number) mx.get(0)).doubleValue(),
              ((Number) mx.get(1)).doubleValue(),
              ((Number) mx.get(2)).doubleValue());
      Pose3d pose = new Pose3d();
      if (item.get("poseMeters") instanceof List<?> p && p.size() >= 3) {
        Translation3d t =
            new Translation3d(
                ((Number) p.get(0)).doubleValue(),
                ((Number) p.get(1)).doubleValue(),
                ((Number) p.get(2)).doubleValue());
        Rotation3d r = new Rotation3d();
        if (item.get("rpyRadians") instanceof List<?> rpy && rpy.size() >= 3) {
          r =
              new Rotation3d(
                  ((Number) rpy.get(0)).doubleValue(),
                  ((Number) rpy.get(1)).doubleValue(),
                  ((Number) rpy.get(2)).doubleValue());
        }
        pose = new Pose3d(t, r);
      }
      result.add(new FieldObstacle3d(name, bounds, pose, target));
    }
    return List.copyOf(result);
  }
}
